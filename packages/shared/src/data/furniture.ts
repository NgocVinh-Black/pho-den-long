export const MAX_TABLES = 4;

/** Danh mục đồ quán xá của một kiểu quán. */
export const furnitureFor = (interior: InteriorKind): FurnitureItem[] =>
  FURNITURE.filter((f) => f.interior === interior);

/** Món của kiểu quán đảm nhận một vai. */
export const furnitureByRole = (interior: InteriorKind, role: FurnitureRole): FurnitureItem | undefined =>
  FURNITURE.find((f) => f.interior === interior && f.role === role);

/** Bộ khởi đầu: 1 cụm chỗ ngồi thường của kiểu quán. */
export function starterFurniture(interior: InteriorKind): Record<string, number> {
  const seat = furnitureByRole(interior, 'seat');
  return seat ? { [seat.id]: 1 } : {};
}

/**
 * Bản lưu cũ (trước khi tách danh mục) chỉ có đồ quán ăn. Đổi một món sang món cùng vai của kiểu quán.
 * Trả về chính id nếu món đã thuộc kiểu quán, null nếu không đổi được.
 */
export function migrateFurnitureId(itemId: string, interior: InteriorKind): string | null {
  const item = FURNITURE.find((f) => f.id === itemId);
  if (!item) return null;
  if (item.interior === interior) return item.id;
  return furnitureByRole(interior, item.role)?.id ?? null;
}

/** Tên hiển thị của món ở một quán cụ thể (ưu tiên tên riêng theo quán). */
export const furnitureName = (item: Pick<FurnitureItem, 'name' | 'names'>, shopId: string): string =>
  item.names?.[shopId] ?? item.name;
